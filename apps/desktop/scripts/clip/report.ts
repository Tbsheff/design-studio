import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

import { isFile } from "./steps.ts";
import { FINDING_KINDS } from "./types.ts";
import type { Finding, FindingKind } from "./types.ts";

type KindCounts = Record<FindingKind, number>;

interface ClipBaseline {
  readonly counts: KindCounts;
  readonly total: number;
}

const TOP_COUNT = 10;

const toCounts = (findings: readonly Finding[]): KindCounts => {
  const counts: KindCounts = {
    clipped: 0,
    overlap: 0,
    "sideways-scroll": 0,
    "text-overflow": 0,
    unreachable: 0,
  };

  for (const finding of findings) {
    counts[finding.kind] += 1;
  }

  return counts;
};

const toCell = (value: string): string =>
  value.replaceAll("|", String.raw`\|`).replaceAll("\n", " ");

const toCropLink = (finding: Finding): string => {
  if (finding.crop === null) {
    return "";
  }

  return ` [crop](crops/${finding.crop})`;
};

const toAlso = (finding: Finding): string => {
  const others = finding.states.length - 1;

  if (others <= 0) {
    return "";
  }

  return ` (+${others} more states)`;
};

const toFindingLine = (finding: Finding): string => {
  const crop = toCropLink(finding);
  const also = toAlso(finding);

  return `- \`${toCell(finding.selector)}\` "${toCell(finding.text)}": ${finding.detail}. ${finding.mode}${also}.${crop}`;
};

const toStateLines = (state: string, ofKind: readonly Finding[]): string[] => {
  const lines = ofKind
    .filter((finding) => finding.state === state)
    .toSorted((one, two) => two.amount - one.amount)
    .map((finding) => toFindingLine(finding));

  return [`### ${state}`, "", ...lines, ""];
};

const toKindSection = (
  kind: FindingKind,
  findings: readonly Finding[]
): string[] => {
  const ofKind = findings.filter((finding) => finding.kind === kind);

  const states = [
    ...new Set(ofKind.map((finding) => finding.state)),
  ].toSorted();

  return [
    `## ${kind} (${ofKind.length})`,
    "",
    ...states.flatMap((state) => toStateLines(state, ofKind)),
  ];
};

const toWorst = (findings: readonly Finding[]): Finding[] => {
  const worst = new Map<string, Finding>();

  for (const finding of findings) {
    const key = `${finding.kind}|${finding.selector}`;
    const prior = worst.get(key) ?? null;

    if (
      finding.kind !== "unreachable" &&
      (prior === null || finding.amount > prior.amount)
    ) {
      worst.set(key, finding);
    }
  }

  return [...worst.values()].toSorted((one, two) => two.amount - one.amount);
};

const toTopLines = (findings: readonly Finding[]): string[] =>
  toWorst(findings)
    .slice(0, TOP_COUNT)
    .map(
      (finding, index) =>
        `${index + 1}. ${finding.kind} ${finding.amount} px: \`${toCell(finding.selector)}\` in ${finding.state}, ${finding.mode} (worst size and theme)`
    );

const exportReport = async (
  findings: readonly Finding[],
  out: string,
  stateCount: number
): Promise<string> => {
  const counts = toCounts(findings);
  const file = path.join(out, "report.md");

  const lines = [
    "# Clip check",
    "",
    `Generated by \`pnpm exec tsx scripts/check-clip.ts\`. ${stateCount} states checked at 1440x900 and 1000x800, dark and light. One finding per kind, selector, size and theme; "more states" counts the other states that show it.`,
    "",
    "Rules: clipped = a visible box goes past the viewport, or past an ancestor with overflow hidden or clip on that axis. Absolute and fixed boxes follow their containing block, top-layer boxes stop at their own root, and scroll containers only cut the visible part (sideways-scroll reports them). CSS tooltips (data-tip ::after) are measured with a copy of the pseudo-element while hovered. text-overflow = a box with scrollWidth > clientWidth + 1 (or scrollHeight > clientHeight + 1) whose own text runs more than 2 px past its padding box, with no ellipsis (or no line clamp); boxes of 4 px or less (screen-reader text) are skipped. overlap = two hit-testable controls in one layer intersect by more than 2 px and neither holds the other. sideways-scroll = overflow-x auto or scroll that scrolls, with no horizontal role. The canvas iframe, clipping inside .stage, aria-hidden, inert and zero-size boxes are ignored.",
    "",
    "| Kind | Count |",
    "| --- | --- |",
    ...FINDING_KINDS.map((kind) => `| ${kind} | ${counts[kind]} |`),
    "",
    "## Top 10",
    "",
    ...toTopLines(findings),
    "",
    ...FINDING_KINDS.flatMap((kind) => toKindSection(kind, findings)),
  ];

  await writeFile(file, `${lines.join("\n")}\n`);

  return file;
};

const getBaseline = async (file: string): Promise<ClipBaseline | null> => {
  if (!(await isFile(file))) {
    return null;
  }

  return JSON.parse(await readFile(file, "utf-8")) as ClipBaseline;
};

const exportBaseline = async (
  file: string,
  findings: readonly Finding[]
): Promise<void> => {
  const baseline: ClipBaseline = {
    counts: toCounts(findings),
    total: findings.length,
  };

  await writeFile(file, `${JSON.stringify(baseline, null, 2)}\n`);
};

const toRises = (
  findings: readonly Finding[],
  baseline: ClipBaseline
): string[] => {
  const counts = toCounts(findings);

  return FINDING_KINDS.flatMap((kind) => {
    const before = baseline.counts[kind] ?? 0;

    if (counts[kind] <= before) {
      return [];
    }

    return [`${kind}: ${before} -> ${counts[kind]}`];
  });
};

export {
  exportBaseline,
  exportReport,
  getBaseline,
  toCounts,
  toRises,
  toTopLines,
};

export type { ClipBaseline };
