import { readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { DESIGN_MD_TOKENS_END, DESIGN_MD_TOKENS_START } from '../../shared/contracts.js';
import type { TokenFile } from '../../shared/contracts.js';
import { OKLCH_SUPPORTS, SYSTEM_DARK_MEDIA, compileTokens, cssVarFor } from './compile.js';
import { upsertTokenBlock } from './design-md.js';

const FIXTURE = path.join(path.dirname(fileURLToPath(import.meta.url)), '__fixtures__', 'test-pack', 'tokens.json');

function fixture(): TokenFile {
  return JSON.parse(readFileSync(FIXTURE, 'utf8')) as TokenFile;
}

function entry(file: TokenFile, tokenPath: string) {
  return compileTokens(file).entries.find((item) => item.path === tokenPath);
}

describe('compileTokens', () => {
  it('compiles the fixture with no errors', () => {
    const result = compileTokens(fixture());
    expect(result.errors).toEqual([]);
    expect(result.css.startsWith('/* Generated by Design Studio')).toBe(true);
  });

  it('maps token paths to css variable names', () => {
    expect(cssVarFor(['color', 'primary'])).toBe('--primary');
    expect(cssVarFor(['font', 'display'])).toBe('--font-display');
    expect(cssVarFor(['text', 'xs'])).toBe('--text-xs');
    expect(cssVarFor(['space', '4'])).toBe('--space-4');
    expect(cssVarFor(['radius', 'md'])).toBe('--radius-md');
    expect(cssVarFor(['shadow', 'md'])).toBe('--shadow-md');
    expect(cssVarFor(['motion', 'fast'])).toBe('--motion-fast');
    const file = fixture();
    file.motion = { $type: 'duration', fast: { $value: '150ms' } };
    const result = compileTokens(file);
    expect(result.errors).toEqual([]);
    expect(result.css).toContain('--motion-fast: 150ms;');
  });

  it('turns aliases into var() and redeclares them in dark mode', () => {
    const result = compileTokens(fixture());
    expect(entry(fixture(), 'color.ring')?.value).toBe('var(--primary)');
    const darkBlock = result.css.slice(result.css.indexOf(':root[data-theme="dark"]'));
    expect(darkBlock).toContain('--ring: var(--primary);');
  });

  it('reports alias cycles and missing alias targets', () => {
    const file = fixture();
    file.color.primary = { $value: '{color.accent}' };
    file.color.accent = { $value: '{color.primary}' };
    file.color.danger = { $value: '{color.nope}' };
    const errors = compileTokens(file).errors.join('\n');
    expect(errors).toMatch(/alias cycle: color\.primary -> color\.accent -> color\.primary/);
    expect(errors).toMatch(/color\.danger: alias \{color\.nope\} points to no token/);
  });

  it('writes dark values to the theme selectors and the system media query for light packs', () => {
    const { css } = compileTokens(fixture(), { mode: 'light' });
    expect(css).toContain(':root[data-theme="dark"],\n.dark {\n  --bg: #111111;');
    expect(css).toContain(`${SYSTEM_DARK_MEDIA} {\n  :root:not([data-theme="light"]) {\n    --bg: #111111;`);
    const darkPack = compileTokens(fixture(), { mode: 'dark' }).css;
    expect(darkPack).toContain(':root[data-theme="dark"]');
    expect(darkPack).not.toContain(SYSTEM_DARK_MEDIA);
  });

  it('puts hex fallbacks first and oklch values inside @supports', () => {
    const { css } = compileTokens(fixture());
    const supportsAt = css.indexOf(OKLCH_SUPPORTS);
    expect(supportsAt).toBeGreaterThan(0);
    expect(css.slice(0, supportsAt)).toContain('--primary: #');
    expect(css.slice(0, supportsAt)).not.toMatch(/--primary: oklch/);
    expect(css.slice(supportsAt)).toContain('--primary: oklch(55% 0.2 260);');
    expect(entry(fixture(), 'color.fg')?.value).toMatch(/^oklch\(/);
  });

  it('keeps a dark alias over a light color in the .dark rule of the oklch layer', () => {
    const file = fixture();
    file.color.surface = { $value: '#fafafa', $extensions: { 'studio.modes': { dark: '{color.bg}' } } };
    const { css, errors } = compileTokens(file);
    expect(errors).toEqual([]);
    const modern = css.slice(css.indexOf(OKLCH_SUPPORTS));
    const modernDark = modern.slice(modern.indexOf('.dark {'), modern.indexOf('}', modern.indexOf('.dark {')));
    expect(modernDark).toContain('--surface: var(--bg);');
  });

  it('clamps wide-gamut colors to a valid sRGB hex', () => {
    const file = fixture();
    file.color.accent = { $value: 'oklch(70% 0.4 145)' };
    const { css, errors } = compileTokens(file);
    expect(errors).toEqual([]);
    expect(css).toMatch(/--accent: #[0-9a-f]{6};/);
  });

  it('reports missing required tokens, bad values and unknown types', () => {
    const file = fixture();
    delete file.color.bg;
    file.space['4'] = { $value: 'sixteen' };
    file.color.border = { $value: 'not-a-color' };
    file.font.body = { $value: 'Inter; } body { color: red' };
    file.extra = { odd: { $type: 'gradient' as never, $value: 'x' } };
    const errors = compileTokens(file).errors.join('\n');
    expect(errors).toContain('missing required token color.bg');
    expect(errors).toContain('space.4: "sixteen" is not a dimension');
    expect(errors).toContain('color.border: "not-a-color" is not a color');
    expect(errors).toContain('font.body: must not contain');
    expect(errors).toContain('extra.odd: unknown $type "gradient"');
  });

  it('infers $type from core group names and errors when no type exists', () => {
    const file = fixture();
    delete file.radius.$type;
    file.misc = { thing: { $value: '1' } };
    const errors = compileTokens(file).errors;
    expect(errors).toEqual(['misc.thing: no $type on the token or its group']);
  });

  it('is deterministic and keeps file order inside a group', () => {
    const first = compileTokens(fixture());
    const second = compileTokens(fixture());
    expect(first.css).toBe(second.css);
    const spaces = first.entries.filter((item) => item.path.startsWith('space.')).map((item) => item.cssVar);
    expect(spaces).toEqual(['--space-1', '--space-2', '--space-3', '--space-4', '--space-5', '--space-6', '--space-8', '--space-10', '--space-12']);
    const groups = [...new Set(first.entries.map((item) => item.path.split('.')[0]))];
    expect(groups).toEqual(['color', 'font', 'text', 'space', 'radius', 'shadow']);
  });
});

describe('DESIGN.md token block', () => {
  const entries = compileTokens(fixture()).entries;

  it('inserts the block after the first H1 and keeps prose', () => {
    const md = '# Title\n\nIntro prose.\n\n## Colors\n\nMore prose.\n';
    const out = upsertTokenBlock(md, entries);
    expect(out.startsWith(`# Title\n\n${DESIGN_MD_TOKENS_START}\n`)).toBe(true);
    expect(out).toContain(`${DESIGN_MD_TOKENS_END}\n\nIntro prose.\n\n## Colors\n\nMore prose.\n`);
    expect(out).toContain('| `--primary` | oklch(55% 0.2 260) | oklch(70% 0.15 260) | Primary actions. |');
  });

  it('replaces an existing block in place', () => {
    const md = `# T\n\n${DESIGN_MD_TOKENS_START}\nold\n${DESIGN_MD_TOKENS_END}\n\nProse.\n`;
    const out = upsertTokenBlock(md, entries);
    expect(out).not.toContain('\nold\n');
    expect(out.split(DESIGN_MD_TOKENS_START)).toHaveLength(2);
    expect(out.endsWith(`${DESIGN_MD_TOKENS_END}\n\nProse.\n`)).toBe(true);
    expect(upsertTokenBlock(out, entries)).toBe(out);
  });

  it('prepends the block when there is no H1 and escapes pipes', () => {
    const out = upsertTokenBlock('Just text.\n', [{ path: 'x.y', cssVar: '--x-y', type: 'shadow', value: 'a | b', darkValue: null }]);
    expect(out.startsWith(DESIGN_MD_TOKENS_START)).toBe(true);
    expect(out).toContain('| `--x-y` | a \\| b | - | - |');
    expect(out.endsWith('Just text.\n')).toBe(true);
  });
});
