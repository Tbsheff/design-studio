import { clampChroma, converter, formatHex, formatHex8, parse } from 'culori';
import { REQUIRED_TOKENS } from '../../shared/contracts.js';
import type { CompiledTokenEntry, TokenFile, TokenType } from '../../shared/contracts.js';

export type ThemeMode = 'light' | 'dark';

interface CompileOptions {
  mode?: ThemeMode;
  only?: ReadonlySet<string>;
}

interface CompileResult {
  css: string;
  entries: CompiledTokenEntry[];
  errors: string[];
  emitted: string[];
}

const TOKENS_CSS_HEADER = '/* Generated by Design Studio from design-system/tokens.json. Edit tokens.json, not this file. */';
export const OKLCH_SUPPORTS = '@supports (color: oklch(0% 0 0))';
export const DARK_SELECTOR = ':root[data-theme="dark"],\n.dark';
export const SYSTEM_DARK_MEDIA = '@media (prefers-color-scheme: dark)';
const SYSTEM_DARK_SELECTOR = ':root:not([data-theme="light"])';

const CORE_GROUPS = ['color', 'font', 'text', 'space', 'radius', 'shadow', 'breakpoint'] as const;
const GROUP_DEFAULT_TYPES: Record<string, TokenType> = {
  color: 'color',
  font: 'fontFamily',
  text: 'dimension',
  space: 'dimension',
  radius: 'dimension',
  shadow: 'shadow',
  breakpoint: 'dimension',
};
const TOKEN_TYPES = new Set<TokenType>(['color', 'dimension', 'fontFamily', 'fontWeight', 'number', 'shadow', 'duration']);
const NAME_PATTERN = /^[A-Za-z0-9_-]+$/;
const WHOLE_ALIAS = /^\{([A-Za-z0-9_.-]+)\}$/;
const ANY_ALIAS = /\{([A-Za-z0-9_.-]+)\}/g;
const UNSAFE_VALUE = /[;{}<>\\]/;
const DIMENSION = /^(0|-?(\d+\.?\d*|\.\d+)(px|rem|em|%|vh|vw|vmin|vmax|ch|ex|lh|rlh))$/;
const CSS_MATH = /^(calc|clamp|min|max)\([A-Za-z0-9 .,%+*/()-]+\)$/;
const NUMBER = /^-?(\d+\.?\d*|\.\d+)$/;
const DURATION = /^(\d+\.?\d*|\.\d+)(ms|s)$/;
const FONT_WEIGHT_KEYWORDS = new Set(['normal', 'bold', 'lighter', 'bolder']);
const toOklch = converter('oklch');

interface RawToken {
  path: string;
  group: string;
  cssVar: string;
  type: TokenType;
  light: string;
  dark: string | null;
  description?: string;
}

interface ResolvedValue {
  css: string;
  hex: string | null;
  refs: string[];
}

interface CompiledToken {
  raw: RawToken;
  light: ResolvedValue;
  dark: ResolvedValue | null;
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function round(value: number, places: number): string {
  return String(Number(value.toFixed(places)));
}

function groupOrder(file: TokenFile): string[] {
  const extras = Object.keys(file)
    .filter((key) => !key.startsWith('$') && !(CORE_GROUPS as readonly string[]).includes(key))
    .sort();
  return [...CORE_GROUPS, ...extras];
}

export function cssVarFor(segments: string[]): string {
  const [group, ...rest] = segments;
  return group === 'color' ? `--${rest.join('-')}` : `--${segments.join('-')}`;
}

function scalarString(value: unknown): string | null {
  if (typeof value === 'string') return value.trim();
  if (typeof value === 'number' && Number.isFinite(value)) return String(value);
  return null;
}

function tokenType(node: Record<string, unknown>, inherited: TokenType | undefined, group: string, where: string, errors: string[]): TokenType | null {
  const declared = node.$type ?? inherited ?? GROUP_DEFAULT_TYPES[group];
  if (declared === undefined) {
    errors.push(`${where}: no $type on the token or its group`);
    return null;
  }
  if (!TOKEN_TYPES.has(declared as TokenType)) {
    errors.push(`${where}: unknown $type "${String(declared)}"`);
    return null;
  }
  return declared as TokenType;
}

function darkOf(node: Record<string, unknown>, where: string, errors: string[]): string | null {
  const extensions = node.$extensions;
  if (!isRecord(extensions) || !isRecord(extensions['studio.modes'])) return null;
  const dark = extensions['studio.modes'].dark;
  if (dark === undefined) return null;
  const value = scalarString(dark);
  if (value === null || value === '') errors.push(`${where}: dark value must be a string`);
  return value || null;
}

function readToken(node: Record<string, unknown>, segments: string[], inherited: TokenType | undefined, errors: string[]): RawToken | null {
  const where = segments.join('.');
  const group = segments[0] ?? '';
  const type = tokenType(node, inherited, group, where, errors);
  const light = scalarString(node.$value);
  if (light === null || light === '') errors.push(`${where}: $value must be a non-empty string`);
  const dark = darkOf(node, where, errors);
  if (type === null || light === null || light === '') return null;
  const token: RawToken = { path: where, group, cssVar: cssVarFor(segments), type, light, dark };
  if (typeof node.$description === 'string') token.description = node.$description;
  return token;
}

function walkGroup(node: Record<string, unknown>, segments: string[], inherited: TokenType | undefined, out: RawToken[], errors: string[]): void {
  const groupType = (node.$type as TokenType | undefined) ?? inherited;
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith('$')) continue;
    const childSegments = [...segments, key];
    if (!NAME_PATTERN.test(key)) {
      errors.push(`${childSegments.join('.')}: name must use letters, digits, "-" or "_"`);
      continue;
    }
    if (!isRecord(child)) {
      errors.push(`${childSegments.join('.')}: must be a token object or a group`);
      continue;
    }
    if ('$value' in child) {
      const token = readToken(child, childSegments, groupType, errors);
      if (token) out.push(token);
    } else {
      walkGroup(child, childSegments, (child.$type as TokenType | undefined) ?? groupType, out, errors);
    }
  }
}

function collectTokens(file: TokenFile, errors: string[]): RawToken[] {
  const tokens: RawToken[] = [];
  for (const group of groupOrder(file)) {
    const node = file[group];
    if (node === undefined) continue;
    if (!isRecord(node)) {
      errors.push(`${group}: group must be an object`);
      continue;
    }
    walkGroup(node, [group], node.$type as TokenType | undefined, tokens, errors);
  }
  return tokens;
}

function checkDuplicates(tokens: RawToken[], errors: string[]): void {
  const seen = new Map<string, string>();
  for (const token of tokens) {
    const previous = seen.get(token.cssVar);
    if (previous) errors.push(`${token.path}: css variable ${token.cssVar} is also used by ${previous}`);
    else seen.set(token.cssVar, token.path);
  }
}

function checkRequired(byPath: Map<string, RawToken>, errors: string[]): void {
  for (const [group, names] of Object.entries(REQUIRED_TOKENS)) {
    for (const name of names) {
      const token = byPath.get(`${group}.${name}`);
      const expected = GROUP_DEFAULT_TYPES[group];
      if (!token) errors.push(`missing required token ${group}.${name}`);
      else if (token.type !== expected) errors.push(`${group}.${name}: required token must have $type ${expected}, not ${token.type}`);
    }
  }
}

function aliasRefs(value: string): string[] {
  return [...value.matchAll(ANY_ALIAS)].map((match) => match[1] ?? '');
}

function findCycle(start: string, edges: Map<string, string[]>): string[] | null {
  const stack: string[] = [];
  const visit = (node: string): string[] | null => {
    const index = stack.indexOf(node);
    if (index >= 0) return [...stack.slice(index), node];
    stack.push(node);
    for (const next of edges.get(node) ?? []) {
      const cycle = visit(next);
      if (cycle) return cycle;
    }
    stack.pop();
    return null;
  };
  return visit(start);
}

function checkCycles(tokens: RawToken[], errors: string[]): Set<string> {
  const edges = new Map<string, string[]>();
  for (const token of tokens) edges.set(token.path, [...aliasRefs(token.light), ...aliasRefs(token.dark ?? '')]);
  const inCycle = new Set<string>();
  for (const token of tokens) {
    if (inCycle.has(token.path)) continue;
    const cycle = findCycle(token.path, edges);
    if (cycle && cycle[0] === token.path) {
      errors.push(`alias cycle: ${cycle.join(' -> ')}`);
      for (const node of cycle) inCycle.add(node);
    }
  }
  return inCycle;
}

function formatOklch(value: string): { css: string; hex: string } | null {
  const parsed = parse(value);
  if (!parsed) return null;
  const color = toOklch(parsed);
  const alpha = color.alpha ?? 1;
  const hue = Number.isFinite(color.h) ? (color.h as number) : 0;
  const alphaPart = alpha < 1 ? ` / ${round(alpha, 3)}` : '';
  const css = `oklch(${round(color.l * 100, 2)}% ${round(color.c, 4)} ${round(hue, 2)}${alphaPart})`;
  const inGamut = clampChroma(color, 'oklch');
  const hex = alpha < 1 ? formatHex8(inGamut) : formatHex(inGamut);
  return { css, hex };
}

function checkLiteral(type: TokenType, value: string): string | null {
  if (UNSAFE_VALUE.test(value)) return 'must not contain ; { } < > or \\';
  if (type === 'dimension' && !DIMENSION.test(value) && !CSS_MATH.test(value)) return `"${value}" is not a dimension (for example 16px or 1rem)`;
  if (type === 'number' && !NUMBER.test(value)) return `"${value}" is not a number`;
  if (type === 'duration' && !DURATION.test(value)) return `"${value}" is not a duration (for example 150ms)`;
  if (type === 'fontWeight' && !FONT_WEIGHT_KEYWORDS.has(value) && !(NUMBER.test(value) && Number(value) >= 1 && Number(value) <= 1000)) {
    return `"${value}" is not a font weight`;
  }
  return null;
}

function resolveAlias(ref: string, token: RawToken, byPath: Map<string, RawToken>): ResolvedValue | string {
  const target = byPath.get(ref);
  if (!target) return `alias {${ref}} points to no token`;
  if (target.type !== token.type) return `alias {${ref}} has $type ${target.type}, expected ${token.type}`;
  return { css: `var(${target.cssVar})`, hex: null, refs: [ref] };
}

function substituteAliases(value: string, byPath: Map<string, RawToken>): { text: string; refs: string[]; missing: string | null } {
  const refs: string[] = [];
  let missing: string | null = null;
  const text = value.replace(ANY_ALIAS, (_match, ref: string) => {
    const target = byPath.get(ref);
    if (!target) missing ??= ref;
    refs.push(ref);
    return target ? `var(${target.cssVar})` : '';
  });
  return { text, refs, missing };
}

function resolveValue(value: string, token: RawToken, byPath: Map<string, RawToken>): ResolvedValue | string {
  const whole = WHOLE_ALIAS.exec(value);
  if (whole) return resolveAlias(whole[1] ?? '', token, byPath);
  if (token.type === 'color') {
    const color = formatOklch(value);
    return color ? { ...color, refs: [] } : `"${value}" is not a color (use oklch(), hex, rgb() or hsl())`;
  }
  const substituted = substituteAliases(value, byPath);
  if (substituted.missing) return `alias {${substituted.missing}} points to no token`;
  if (substituted.refs.length > 0 && token.type !== 'shadow' && token.type !== 'fontFamily') {
    return 'only a whole-value alias is allowed for this $type';
  }
  const problem = checkLiteral(token.type, substituted.text);
  return problem ?? { css: substituted.text, hex: null, refs: substituted.refs };
}

function compileToken(token: RawToken, byPath: Map<string, RawToken>, errors: string[]): CompiledToken | null {
  const light = resolveValue(token.light, token, byPath);
  if (typeof light === 'string') errors.push(`${token.path}: ${light}`);
  const dark = token.dark === null ? null : resolveValue(token.dark, token, byPath);
  if (typeof dark === 'string') errors.push(`${token.path} (dark): ${dark}`);
  if (typeof light === 'string' || typeof dark === 'string') return null;
  return { raw: token, light, dark };
}

function followsDark(path: string, byPath: Map<string, CompiledToken>, seen: Set<string> = new Set()): boolean {
  if (seen.has(path)) return false;
  seen.add(path);
  const token = byPath.get(path);
  if (!token) return false;
  if (token.dark) return true;
  return token.light.refs.some((ref) => followsDark(ref, byPath, seen));
}

function declaration(cssVar: string, value: string): string {
  return `  ${cssVar}: ${value};`;
}

function rule(selector: string, lines: string[]): string[] {
  if (lines.length === 0) return [];
  return [`${selector} {`, ...lines, '}'];
}

function wrap(header: string, body: string[]): string[] {
  if (body.length === 0) return [];
  return [`${header} {`, ...body.flatMap((line) => line.split('\n')).map((line) => `  ${line}`), '}'];
}

interface Layers {
  baseLight: string[];
  baseDark: string[];
  modernLight: string[];
  modernDark: string[];
}

function buildLayers(compiled: CompiledToken[], byPath: Map<string, CompiledToken>): Layers {
  const layers: Layers = { baseLight: [], baseDark: [], modernLight: [], modernDark: [] };
  for (const token of compiled) {
    const { cssVar } = token.raw;
    layers.baseLight.push(declaration(cssVar, token.light.hex ?? token.light.css));
    if (token.light.hex) layers.modernLight.push(declaration(cssVar, token.light.css));
    if (token.dark) {
      layers.baseDark.push(declaration(cssVar, token.dark.hex ?? token.dark.css));
      if (token.dark.hex || token.light.hex) layers.modernDark.push(declaration(cssVar, token.dark.css));
    } else if (token.light.refs.some((ref) => followsDark(ref, byPath))) {
      layers.baseDark.push(declaration(cssVar, token.light.css));
    }
  }
  return layers;
}

function dependentsOf(changed: ReadonlySet<string>, compiled: CompiledToken[]): Set<string> {
  const affected = new Set(changed);
  let grew = true;
  while (grew) {
    grew = false;
    for (const token of compiled) {
      if (affected.has(token.raw.path)) continue;
      const refs = [...token.light.refs, ...(token.dark?.refs ?? [])];
      if (!refs.some((ref) => affected.has(ref))) continue;
      affected.add(token.raw.path);
      grew = true;
    }
  }
  return affected;
}

function buildPreviewLayers(compiled: CompiledToken[]): Layers {
  const layers: Layers = { baseLight: [], baseDark: [], modernLight: [], modernDark: [] };
  for (const token of compiled) {
    const { cssVar } = token.raw;
    const dark = token.dark ?? token.light;
    layers.baseLight.push(declaration(cssVar, token.light.hex ?? token.light.css));
    layers.baseDark.push(declaration(cssVar, dark.hex ?? dark.css));
    if (token.light.hex) layers.modernLight.push(declaration(cssVar, token.light.css));
    if (dark.hex || token.light.hex) layers.modernDark.push(declaration(cssVar, dark.css));
  }
  return layers;
}

function themeBlock(light: string[], dark: string[], systemDark: boolean): string[] {
  const media = systemDark ? wrap(SYSTEM_DARK_MEDIA, rule(SYSTEM_DARK_SELECTOR, dark)) : [];
  return [...rule(':root', light), ...rule(DARK_SELECTOR, dark), ...media];
}

function renderCss(layers: Layers, mode: ThemeMode): string {
  const systemDark = mode === 'light' && layers.baseDark.length > 0;
  const base = themeBlock(layers.baseLight, layers.baseDark, systemDark);
  const modern = wrap(OKLCH_SUPPORTS, themeBlock(layers.modernLight, layers.modernDark, systemDark));
  return `${[TOKENS_CSS_HEADER, ...base, ...modern].join('\n')}\n`;
}

function toEntry(token: CompiledToken): CompiledTokenEntry {
  const entry: CompiledTokenEntry = {
    path: token.raw.path,
    cssVar: token.raw.cssVar,
    type: token.raw.type,
    value: token.light.css,
    darkValue: token.dark?.css ?? null,
  };
  if (token.raw.description !== undefined) entry.description = token.raw.description;
  return entry;
}

export function compileTokens(file: TokenFile, options: CompileOptions = {}): CompileResult {
  const errors: string[] = [];
  if (!isRecord(file)) return { css: '', entries: [], errors: ['tokens file must be a JSON object'], emitted: [] };
  const tokens = collectTokens(file, errors);
  const rawByPath = new Map(tokens.map((token) => [token.path, token]));
  checkDuplicates(tokens, errors);
  checkRequired(rawByPath, errors);
  const inCycle = checkCycles(tokens, errors);
  const compiled = tokens
    .filter((token) => !inCycle.has(token.path))
    .map((token) => compileToken(token, rawByPath, errors))
    .filter((token): token is CompiledToken => token !== null);
  const byPath = new Map(compiled.map((token) => [token.raw.path, token]));
  const entries = compiled.map(toEntry);
  if (options.only === undefined) {
    const css = renderCss(buildLayers(compiled, byPath), options.mode ?? 'light');
    return { css, entries, errors, emitted: compiled.map((token) => token.raw.cssVar) };
  }
  const affected = dependentsOf(options.only, compiled);
  const subset = compiled.filter((token) => affected.has(token.raw.path));
  const css = subset.length === 0 ? '' : renderCss(buildPreviewLayers(subset), options.mode ?? 'light');
  return { css, entries, errors, emitted: subset.map((token) => token.raw.cssVar) };
}

export function parseTokenFile(text: string): { file: TokenFile | null; error: string | null } {
  try {
    const parsed = JSON.parse(text) as unknown;
    if (!isRecord(parsed)) return { file: null, error: 'tokens.json must be a JSON object' };
    return { file: parsed as TokenFile, error: null };
  } catch (error) {
    return { file: null, error: `tokens.json is not valid JSON: ${error instanceof Error ? error.message : String(error)}` };
  }
}

export function resolveEntryValue(entries: CompiledTokenEntry[], entry: CompiledTokenEntry, dark = false): string {
  const byVar = new Map(entries.map((item) => [item.cssVar, item]));
  const valueOf = (item: CompiledTokenEntry) => (dark && item.darkValue ? item.darkValue : item.value);
  let current = entry;
  for (let depth = 0; depth < entries.length; depth++) {
    const match = /^var\((--[A-Za-z0-9_-]+)\)$/.exec(valueOf(current));
    const next = match ? byVar.get(match[1] ?? '') : undefined;
    if (!next) return valueOf(current);
    current = next;
  }
  return valueOf(current);
}
